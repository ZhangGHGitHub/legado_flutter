fn header_map_from_source_json(source_json: &str) -> std::collections::HashMap<String, String> {
    let mut map = std::collections::HashMap::new();
    let Ok(v) = serde_json::from_str::<serde_json::Value>(source_json) else {
        return map;
    };
    if let Some(h) = v.get("header") {
        match h {
            serde_json::Value::Object(o) => {
                for (k, val) in o {
                    let s = match val {
                        serde_json::Value::String(s) => s.clone(),
                        other => other.to_string(),
                    };
                    if !s.is_empty() {
                        map.insert(k.clone(), s);
                    }
                }
            }
            serde_json::Value::String(s) => {
                if let Ok(obj) = serde_json::from_str::<serde_json::Value>(s) {
                    if let serde_json::Value::Object(o) = obj {
                        for (k, val) in o {
                            let s = match val {
                                serde_json::Value::String(s) => s.clone(),
                                other => other.to_string(),
                            };
                            if !s.is_empty() {
                                map.insert(k, s);
                            }
                        }
                    }
                }
            }
            _ => {}
        }
    }
    map
}

fn merge_login_into_map(map: &mut std::collections::HashMap<String, String>, login_header: &str) {
    let t = login_header.trim();
    if t.is_empty() {
        return;
    }
    if let Ok(v) = serde_json::from_str::<serde_json::Value>(t) {
        if let serde_json::Value::Object(o) = v {
            for (k, val) in o {
                let s = match val {
                    serde_json::Value::String(s) => s,
                    other => other.to_string(),
                };
                if !s.is_empty() {
                    map.insert(k, s);
                }
            }
            return;
        }
    }
    map.insert("Cookie".to_string(), t.to_string());
}

fn register_login_check_host_apis(ctx: &Ctx<'_>) -> Result<(), String> {
    let get_hm = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>| -> Result<String, rquickjs::Error> {
            LOGIN_CHECK_CTX.with(|c| {
                Ok(c.borrow()
                    .as_ref()
                    .map(|ctx| {
                        serde_json::to_string(&ctx.header_map).unwrap_or_else(|_| "{}".into())
                    })
                    .unwrap_or_else(|| "{}".into()))
            })
        }
    })
    .map_err(|e| format!("注册 lc getHeaderMap 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_header_map_json", get_hm)
        .map_err(|e| format!("注入 lc getHeaderMap 失败: {e}"))?;

    let put_h = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, key: String, val: String| {
            LOGIN_CHECK_CTX.with(|c| {
                if let Some(ctx) = c.borrow_mut().as_mut() {
                    ctx.header_map.insert(key, val);
                }
            });
            Ok::<(), rquickjs::Error>(())
        }
    })
    .map_err(|e| format!("注册 lc putHeader 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_header_put", put_h)
        .map_err(|e| format!("注入 lc putHeader 失败: {e}"))?;

    let put_all = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, json: String| {
            LOGIN_CHECK_CTX.with(|c| {
                if let Some(ctx) = c.borrow_mut().as_mut() {
                    merge_login_into_map(&mut ctx.header_map, &json);
                }
            });
            Ok::<(), rquickjs::Error>(())
        }
    })
    .map_err(|e| format!("注册 lc putAll 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_header_put_all", put_all)
        .map_err(|e| format!("注入 lc putAll 失败: {e}"))?;

    let get_lh = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>| -> Result<String, rquickjs::Error> {
            LOGIN_CHECK_CTX.with(|c| {
                Ok(c.borrow()
                    .as_ref()
                    .map(|ctx| {
                        if !ctx.login_header.is_empty() {
                            ctx.login_header.clone()
                        } else {
                            crate::http::login_header_store::get(&ctx.source_key)
                        }
                    })
                    .unwrap_or_default())
            })
        }
    })
    .map_err(|e| format!("注册 getLoginHeader 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_get_login_header", get_lh)
        .map_err(|e| format!("注入 getLoginHeader 失败: {e}"))?;

    let put_lh = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, header: String| {
            LOGIN_CHECK_CTX.with(|c| {
                if let Some(ctx) = c.borrow_mut().as_mut() {
                    ctx.login_header = header.clone();
                    ctx.login_header_dirty = true;
                    crate::http::login_header_store::put(&ctx.source_key, &header);
                    merge_login_into_map(&mut ctx.header_map, &header);
                    // Cookie → jar（BaseSource.putLoginHeader）
                    if let Ok(v) = serde_json::from_str::<serde_json::Value>(&header) {
                        if let Some(cookie) = v
                            .get("Cookie")
                            .or_else(|| v.get("cookie"))
                            .and_then(|x| x.as_str())
                        {
                            crate::http::client::replace_cookie_for_source(&ctx.source_key, cookie);
                        }
                    } else if header.contains('=') {
                        crate::http::client::replace_cookie_for_source(&ctx.source_key, &header);
                    }
                    AJAX_LOGIN_HEADER.with(|r| *r.borrow_mut() = header);
                }
            });
            Ok::<(), rquickjs::Error>(())
        }
    })
    .map_err(|e| format!("注册 putLoginHeader 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_put_login_header", put_lh)
        .map_err(|e| format!("注入 putLoginHeader 失败: {e}"))?;

    let src_hm = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, has_login: bool| -> Result<String, rquickjs::Error> {
            LOGIN_CHECK_CTX.with(|c| {
                let borrowed = c.borrow();
                let Some(ctx) = borrowed.as_ref() else {
                    return Ok("{}".into());
                };
                let mut map = header_map_from_source_json(&ctx.source_json);
                if has_login {
                    let lh = if !ctx.login_header.is_empty() {
                        ctx.login_header.clone()
                    } else {
                        crate::http::login_header_store::get(&ctx.source_key)
                    };
                    merge_login_into_map(&mut map, &lh);
                }
                Ok(serde_json::to_string(&map).unwrap_or_else(|_| "{}".into()))
            })
        }
    })
    .map_err(|e| format!("注册 source.getHeaderMap 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_source_header_map", src_hm)
        .map_err(|e| format!("注入 source.getHeaderMap 失败: {e}"))?;

    let init_url = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>| {
            // 对齐 AnalyzeUrl.initUrl 轻量版：用最新登录头刷新 header_map（URL 已在外层解析）
            LOGIN_CHECK_CTX.with(|c| {
                if let Some(ctx) = c.borrow_mut().as_mut() {
                    merge_login_into_map(&mut ctx.header_map, &ctx.login_header);
                }
            });
            Ok::<(), rquickjs::Error>(())
        }
    })
    .map_err(|e| format!("注册 initUrl 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_init_url", init_url)
        .map_err(|e| format!("注入 initUrl 失败: {e}"))?;

    let get_str = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>| -> Result<String, rquickjs::Error> {
            let (url, method, body, charset, headers) = LOGIN_CHECK_CTX.with(|c| {
                let ctx = c.borrow();
                let Some(ctx) = ctx.as_ref() else {
                    return (
                        String::new(),
                        "GET".into(),
                        None,
                        "UTF-8".into(),
                        std::collections::HashMap::new(),
                    );
                };
                (
                    ctx.url.clone(),
                    ctx.method.clone(),
                    ctx.req_body.clone(),
                    ctx.charset.clone(),
                    ctx.header_map.clone(),
                )
            });
            if url.is_empty() {
                return Ok(r#"{"body":"","url":"","code":500}"#.into());
            }
            match crate::http::client::fetch_blocking_with_header_map(
                &url,
                &method,
                body.as_deref(),
                &charset,
                &headers,
            ) {
                Ok((code, body)) => Ok(serde_json::json!({
                    "body": body,
                    "url": url,
                    "code": code,
                })
                .to_string()),
                Err(e) => Ok(serde_json::json!({
                    "body": format!("Error Response\n{e}"),
                    "url": url,
                    "code": 500,
                })
                .to_string()),
            }
        }
    })
    .map_err(|e| format!("注册 getStrResponse 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_get_str_response", get_str)
        .map_err(|e| format!("注入 getStrResponse 失败: {e}"))?;

    let start_browser = Function::new(ctx.clone(), {
        move |ctx: Ctx<'_>,
              url: String,
              title: String,
              refetch_after_success: bool,
              has_html: bool,
              html: String|
              -> Result<String, rquickjs::Error> {
            if url.encode_utf16().count() >= 64 * 1024 {
                return Err(Exception::throw_message(
                    &ctx,
                    "startBrowser parameter url too long",
                ));
            }
            let (source_key, mut headers) = LOGIN_CHECK_CTX.with(|c| {
                let borrowed = c.borrow();
                borrowed
                    .as_ref()
                    .map(|state| (state.source_key.clone(), state.header_map.clone()))
                    .unwrap_or_default()
            });
            let config = crate::http::client::parse_url_config(&url, "");
            headers.extend(config.headers.clone());
            let mut initial_html = has_html.then_some(html);
            if initial_html.is_none() && config.method.eq_ignore_ascii_case("POST") {
                initial_html = Some(
                    crate::http::client::fetch_blocking_with_header_map(
                        &config.url,
                        &config.method,
                        config.body.as_deref(),
                        &config.charset,
                        &headers,
                    )
                    .map_err(|e| Exception::throw_message(&ctx, &e))?
                    .1,
                );
            }
            let response = crate::browser_host::invoke(crate::api::SourceBrowserRequestDto {
                source_key,
                url: config.url.clone(),
                title,
                html: initial_html.clone(),
                headers: headers.clone(),
                refetch_after_success,
            })
            .map_err(|e| Exception::throw_message(&ctx, &e))?;

            let (final_url, body) = if refetch_after_success {
                if let Some(html) = initial_html {
                    (config.url, html)
                } else {
                    let (_, body, final_url) =
                        crate::http::client::fetch_blocking_response_with_header_map(
                            &config.url,
                            &config.method,
                            config.body.as_deref(),
                            &config.charset,
                            &headers,
                        )
                        .map_err(|e| Exception::throw_message(&ctx, &e))?;
                    (final_url, body)
                }
            } else {
                let final_url = if response.final_url.trim().is_empty() {
                    config.url
                } else {
                    response.final_url
                };
                (final_url, response.body)
            };
            Ok(serde_json::json!({
                "body": body,
                "url": final_url,
                "code": 200,
            })
            .to_string())
        }
    })
    .map_err(|e| format!("注册 startBrowserAwait 失败: {e}"))?;
    ctx.globals()
        .set("__legado_lc_start_browser", start_browser)
        .map_err(|e| format!("注入 startBrowserAwait 失败: {e}"))?;

    Ok(())
}

/// 对齐 Jingshiro：`AnalyzeUrl.getStrResponseAwait` 之后执行 `loginCheckJs`。
///
/// 绑定清单（reference/Jingshiro-legado）：
/// - `result` = StrResponse；`java` ≈ AnalyzeUrl（getHeaderMap / initUrl / getStrResponse）
/// - `source.putLoginHeader` / `getLoginHeader` / `getHeaderMap(true)`
pub fn apply_login_check_js(
    source_json: &str,
    body: &str,
    request_url: &str,
    method: &str,
    req_body: Option<&str>,
    charset: &str,
) -> LoginCheckResult {
    let script = login_check_js_from_source_json(source_json);
    let script = script.trim();
    let fallback = LoginCheckResult {
        body: body.to_string(),
        url: request_url.to_string(),
        login_header: None,
    };
    if script.is_empty() {
        return fallback;
    }
    let js_lib = js_lib_from_source_json(source_json);
    match run_login_check_script(
        script,
        body,
        &js_lib,
        request_url,
        source_json,
        method,
        req_body,
        charset,
    ) {
        Ok(out) => {
            if out.body.is_empty() {
                LoginCheckResult {
                    body: body.to_string(),
                    url: out.url,
                    login_header: out.login_header,
                }
            } else {
                out
            }
        }
        Err(e) => {
            eprintln!("[loginCheckJs] 执行失败（保留原响应）: {e}");
            fallback
        }
    }
}

/// 在专用阻塞线程执行同步 QuickJS。Dart 主 isolate 可在原 FRB Future 挂起期间处理 WebView 回调。
pub async fn apply_login_check_js_async(
    source_json: &str,
    body: &str,
    request_url: &str,
    method: &str,
    req_body: Option<&str>,
    charset: &str,
) -> LoginCheckResult {
    let source_json = source_json.to_string();
    let body = body.to_string();
    let request_url = request_url.to_string();
    let method = method.to_string();
    let req_body = req_body.map(str::to_string);
    let charset = charset.to_string();
    let fallback = LoginCheckResult {
        body: body.clone(),
        url: request_url.clone(),
        login_header: None,
    };
    tokio::task::spawn_blocking(move || {
        apply_login_check_js(
            &source_json,
            &body,
            &request_url,
            &method,
            req_body.as_deref(),
            &charset,
        )
    })
    .await
    .unwrap_or_else(|e| {
        eprintln!("[loginCheckJs] 阻塞线程失败（保留原响应）: {e}");
        fallback
    })
}

