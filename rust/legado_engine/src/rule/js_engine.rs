fn run_with_result_opts_internal(
    script: &str,
    result: &str,
    js_lib: &str,
    base_url: &str,
    book_url: Option<&str>,
    book_name: Option<&str>,
    book_author: Option<&str>,
    as_string: bool,
) -> Result<String, String> {
    let script = normalize_rhino_with(script);
    with_js_context(script.as_ref(), js_lib, |ctx| {
        init_context(&ctx, js_lib, base_url)?;
        let escaped = serde_json::to_string(result).unwrap_or_else(|_| "\"\"".to_string());
        let book_url = book_url.unwrap_or(base_url);
        let book_inject = format!(
            "var book = {{ bookUrl: {}, name: {}, author: {} }};\n",
            json_escape(book_url),
            json_escape(book_name.unwrap_or("")),
            json_escape(book_author.unwrap_or("")),
        );
        let code = format!(
            "{book_inject}legadoResult = {escaped}; var result = typeof legadoResult === 'string' ? legadoResult : JSON.stringify(legadoResult);\n{script}"
        );
        let v: Value = ctx
            .eval(code.as_bytes())
            .catch(&ctx)
            .map_err(|e| format_caught_err("JS 执行失败", e))?;
        if as_string {
            value_to_js_string(&ctx, v)
        } else {
            value_to_string(&ctx, v)
        }
    })
}

fn normalize_rhino_with(script: &str) -> std::borrow::Cow<'_, str> {
    static WITH_BLOCK: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
    static IMPLICIT_FOR_OF: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
    let with_block =
        WITH_BLOCK.get_or_init(|| regex::Regex::new(r"(?i)\bwith\s*\([^)]*\)\s*\{").unwrap());
    let implicit_for_of = IMPLICIT_FOR_OF.get_or_init(|| {
        regex::Regex::new(r"\bfor\s*\(\s*([A-Za-z_$][A-Za-z0-9_$]*)\s+of\s+").unwrap()
    });
    if !with_block.is_match(script) && !implicit_for_of.is_match(script) {
        return std::borrow::Cow::Borrowed(script);
    }
    let without_with = with_block.replace_all(script, "{");
    std::borrow::Cow::Owned(
        implicit_for_of
            .replace_all(without_with.as_ref(), "for (var $1 of ")
            .into_owned(),
    )
}

/// 纯 property 规则名（如 `chaptername` / `chapterurl`），无 CSS/`@`
pub fn is_plain_property_rule(rule: &str) -> bool {
    let r = rule.trim();
    !r.is_empty()
        && !r.contains('@')
        && !r.contains('<')
        && !r.contains('.')
        && !r.contains('#')
        && !r.contains(' ')
        && !r.contains(':')
        && r.chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
}

