/// 将 QuickJS CaughtError 展开为可读信息（避免仅见 "Exception generated by QuickJS"）
fn format_caught_err(prefix: &str, err: CaughtError<'_>) -> String {
    match err {
        CaughtError::Exception(ex) => {
            let msg = ex.message().unwrap_or_default();
            let stack = ex.stack().unwrap_or_default();
            if msg.eq_ignore_ascii_case("interrupted") {
                return format!(
                    "{prefix}: JS 执行超时（超过 {} 秒）",
                    JS_EXECUTION_TIMEOUT.as_secs()
                );
            }
            if !msg.is_empty() && !stack.is_empty() {
                format!("{prefix}: {msg}\n{stack}")
            } else if !msg.is_empty() {
                format!("{prefix}: {msg}")
            } else {
                format!("{prefix}: {ex}")
            }
        }
        CaughtError::Value(v) => format!("{prefix}: {v:?}"),
        CaughtError::Error(e) => format!("{prefix}: {e}"),
    }
}

fn with_js_context<T>(
    script: &str,
    js_lib: &str,
    operation: impl for<'js> FnOnce(Ctx<'js>) -> Result<T, String>,
) -> Result<T, String> {
    for (label, value) in [("脚本", script), ("jsLib", js_lib)] {
        if value.len() > MAX_JS_INPUT_BYTES {
            return Err(format!(
                "JS 执行失败: {label}输入超过 {} 字节上限（实际 {} 字节）",
                MAX_JS_INPUT_BYTES,
                value.len()
            ));
        }
    }

    let rt = Runtime::new().map_err(|e| format!("JS Runtime 失败: {e}"))?;
    let deadline = Instant::now() + JS_EXECUTION_TIMEOUT;
    rt.set_interrupt_handler(Some(Box::new(move || Instant::now() >= deadline)));
    let ctx = Context::full(&rt).map_err(|e| format!("JS Context 失败: {e}"))?;
    ctx.with(operation)
}

fn register_host_apis(ctx: &Ctx<'_>) -> Result<(), String> {
    let base64_encode = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, value: String| {
            Ok::<String, rquickjs::Error>(
                base64::engine::general_purpose::STANDARD.encode(value.as_bytes()),
            )
        }
    })
    .map_err(|e| format!("注册 Base64 encode 失败: {e}"))?;
    ctx.globals()
        .set("__legado_base64_encode", base64_encode)
        .map_err(|e| format!("注入 Base64 encode 失败: {e}"))?;

    let hex_decode = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, value: String| {
            Ok::<String, rquickjs::Error>(decode_hex_or_original(&value))
        }
    })
    .map_err(|e| format!("注册 hex decode 失败: {e}"))?;
    ctx.globals()
        .set("__legado_hex_decode", hex_decode)
        .map_err(|e| format!("注入 hex decode 失败: {e}"))?;

    let jsonpath_read = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, json: String, path: String| {
            let result = serde_json::from_str::<serde_json::Value>(&json)
                .ok()
                .and_then(|value| super::json_util::resolve_path(&value, &path).ok())
                .unwrap_or(serde_json::Value::Null);
            Ok::<String, rquickjs::Error>(
                serde_json::to_string(&result).unwrap_or_else(|_| "null".to_string()),
            )
        }
    })
    .map_err(|e| format!("注册 JSONPath read 失败: {e}"))?;
    ctx.globals()
        .set("__legado_jsonpath_read", jsonpath_read)
        .map_err(|e| format!("注入 JSONPath read 失败: {e}"))?;

    let encrypt = Function::new(ctx.clone(), {
        move |ctx: Ctx<'_>, transformation: String, key: String, iv: String, data: String| {
            match super::js_crypto::encrypt_base64(&transformation, &key, &iv, &data) {
                Ok(s) => Ok(s),
                Err(e) => Err(Exception::throw_message(
                    &ctx,
                    &format!("AES encrypt 失败: {e}"),
                )),
            }
        }
    })
    .map_err(|e| format!("注册 AES encrypt 失败: {e}"))?;
    ctx.globals()
        .set("__legado_aes_encrypt_b64", encrypt)
        .map_err(|e| format!("注入 AES encrypt 失败: {e}"))?;

    let decrypt = Function::new(ctx.clone(), {
        move |ctx: Ctx<'_>, transformation: String, key: String, iv: String, data: String| {
            match super::js_crypto::decrypt_str(&transformation, &key, &iv, &data) {
                Ok(s) => Ok(s),
                Err(e) => Err(Exception::throw_message(
                    &ctx,
                    &format!("AES decrypt 失败: {e}"),
                )),
            }
        }
    })
    .map_err(|e| format!("注册 AES decrypt 失败: {e}"))?;
    ctx.globals()
        .set("__legado_aes_decrypt_str", decrypt)
        .map_err(|e| format!("注入 AES decrypt 失败: {e}"))?;

    // Jingshiro JsExtensions.ajax — 同步拉页面（失败返回空串，调用方常 try/catch）
    let ajax = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, url: String| -> Result<String, rquickjs::Error> {
            let referer = AJAX_REFERER.with(|r| r.borrow().clone());
            let source_json = AJAX_SOURCE_JSON.with(|r| r.borrow().clone());
            let login_header = AJAX_LOGIN_HEADER.with(|r| r.borrow().clone());
            match crate::http::client::ajax_blocking_with_deadline(
                &url,
                if referer.is_empty() {
                    None
                } else {
                    Some(referer.as_str())
                },
                if source_json.is_empty() {
                    None
                } else {
                    Some(source_json.as_str())
                },
                if login_header.is_empty() {
                    None
                } else {
                    Some(login_header.as_str())
                },
                JS_HOST_HTTP_TIMEOUT,
            ) {
                Ok(body) => Ok(body),
                Err(_) => Ok(String::new()),
            }
        }
    })
    .map_err(|e| format!("注册 java.ajax 失败: {e}"))?;
    ctx.globals()
        .set("__legado_java_ajax", ajax)
        .map_err(|e| format!("注入 java.ajax 失败: {e}"))?;

    // Jingshiro `java.ajaxAll`：并发执行 URL，并保持 StrResponse 的方法形状。
    let ajax_all = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, payload: String| -> Result<String, rquickjs::Error> {
            let urls = serde_json::from_str::<Vec<String>>(&payload).unwrap_or_default();
            let referer = AJAX_REFERER.with(|r| r.borrow().clone());
            let source_json = AJAX_SOURCE_JSON.with(|r| r.borrow().clone());
            let login_header = AJAX_LOGIN_HEADER.with(|r| r.borrow().clone());
            let handles = urls.into_iter().map(|url| {
                let referer = referer.clone();
                let source_json = source_json.clone();
                let login_header = login_header.clone();
                std::thread::spawn(move || {
                    let started = Instant::now();
                    let result = crate::http::client::ajax_blocking_with_deadline(
                        &url,
                        if referer.is_empty() {
                            None
                        } else {
                            Some(referer.as_str())
                        },
                        if source_json.is_empty() {
                            None
                        } else {
                            Some(source_json.as_str())
                        },
                        if login_header.is_empty() {
                            None
                        } else {
                            Some(login_header.as_str())
                        },
                        JS_HOST_HTTP_TIMEOUT,
                    );
                    match result {
                        Ok(body) => {
                            let raw = body.clone();
                            serde_json::json!({
                            "body": body,
                            "url": url,
                            "code": 200,
                            "message": "",
                            "headers": {},
                            "raw": raw,
                            "callTime": started.elapsed().as_millis(),
                            })
                        }
                        Err(error) => serde_json::json!({
                            "body": "",
                            "url": url,
                            "code": 0,
                            "message": error,
                            "headers": {},
                            "raw": "",
                            "callTime": started.elapsed().as_millis(),
                        }),
                    }
                })
            });
            let rows = handles
                .map(|handle| {
                    handle.join().unwrap_or_else(|_| {
                        serde_json::json!({
                            "body": "",
                            "url": "",
                            "code": 0,
                            "message": "java.ajaxAll 线程异常",
                            "headers": {},
                            "raw": "",
                            "callTime": 0,
                        })
                    })
                })
                .collect::<Vec<_>>();
            Ok(serde_json::to_string(&rows).unwrap_or_else(|_| "[]".to_string()))
        }
    })
    .map_err(|e| format!("注册 java.ajaxAll 失败: {e}"))?;
    ctx.globals()
        .set("__legado_java_ajax_all", ajax_all)
        .map_err(|e| format!("注入 java.ajaxAll 失败: {e}"))?;

    // 登录/源脚本注入 ajax 上下文（书源 header + 登录头）
    let set_ajax_ctx = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, source_json: String, login_header: String| {
            AJAX_SOURCE_JSON.with(|r| *r.borrow_mut() = source_json);
            AJAX_LOGIN_HEADER.with(|r| *r.borrow_mut() = login_header);
            Ok::<(), rquickjs::Error>(())
        }
    })
    .map_err(|e| format!("注册 set_ajax_ctx 失败: {e}"))?;
    ctx.globals()
        .set("__legado_set_ajax_ctx", set_ajax_ctx)
        .map_err(|e| format!("注入 set_ajax_ctx 失败: {e}"))?;

    // —— loginCheckJs AnalyzeUrl 绑定（对照 reference/.../AnalyzeUrl.kt + jsHelp.md）——
    // java.getHeaderMap / initUrl / getStrResponse
    // source.getLoginHeader / putLoginHeader / getHeaderMap(true)
    register_login_check_host_apis(ctx)?;

    let cache_put = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, key: String, value: String, seconds: i64| {
            super::js_cache::put(&key, &value, seconds);
            Ok::<(), rquickjs::Error>(())
        }
    })
    .map_err(|e| format!("注册 cache.put 失败: {e}"))?;
    ctx.globals()
        .set("__legado_cache_put", cache_put)
        .map_err(|e| format!("注入 cache.put 失败: {e}"))?;

    let cache_get = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, key: String| Ok::<String, rquickjs::Error>(super::js_cache::get(&key))
    })
    .map_err(|e| format!("注册 cache.get 失败: {e}"))?;
    ctx.globals()
        .set("__legado_cache_get", cache_get)
        .map_err(|e| format!("注入 cache.get 失败: {e}"))?;

    let cache_delete = Function::new(ctx.clone(), {
        move |_ctx: Ctx<'_>, key: String| {
            super::js_cache::delete(&key);
            Ok::<(), rquickjs::Error>(())
        }
    })
    .map_err(|e| format!("注册 cache.delete 失败: {e}"))?;
    ctx.globals()
        .set("__legado_cache_delete", cache_delete)
        .map_err(|e| format!("注入 cache.delete 失败: {e}"))?;

    Ok(())
}

fn decode_hex_or_original(value: &str) -> String {
    let compact: String = value.chars().filter(|ch| !ch.is_whitespace()).collect();
    if compact.is_empty()
        || compact.len() % 2 != 0
        || !compact.chars().all(|ch| ch.is_ascii_hexdigit())
    {
        return value.to_string();
    }
    let bytes = compact
        .as_bytes()
        .chunks_exact(2)
        .map(|pair| {
            let text = std::str::from_utf8(pair).ok()?;
            u8::from_str_radix(text, 16).ok()
        })
        .collect::<Option<Vec<_>>>();
    bytes
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .unwrap_or_else(|| value.to_string())
}

fn init_context(ctx: &Ctx<'_>, js_lib: &str, base_url: &str) -> Result<(), String> {
    AJAX_REFERER.with(|r| {
        *r.borrow_mut() = base_url.to_string();
    });
    AJAX_SOURCE_JSON.with(|r| r.borrow_mut().clear());
    AJAX_LOGIN_HEADER.with(|r| r.borrow_mut().clear());
    register_host_apis(ctx)?;
    ctx.eval::<(), _>(STDLIB.as_bytes())
        .catch(ctx)
        .map_err(|e| format_caught_err("JS 标准库加载失败", e))?;
    ctx.eval::<(), _>(JSOUP.as_bytes())
        .catch(ctx)
        .map_err(|e| format_caught_err("Jsoup 兼容层加载失败", e))?;
    let base_code = format!("baseUrl = {};", json_escape(base_url));
    ctx.eval::<(), _>(base_code.as_bytes())
        .catch(ctx)
        .map_err(|e| format_caught_err("baseUrl 注入失败", e))?;
    if !js_lib.trim().is_empty() {
        ctx.eval::<(), _>(js_lib.as_bytes())
            .catch(ctx)
            .map_err(|e| format_caught_err("jsLib 加载失败", e))?;
    }
    Ok(())
}

fn value_to_string<'js>(ctx: &Ctx<'js>, v: Value<'js>) -> Result<String, String> {
    if v.is_null() || v.is_undefined() {
        return Ok(String::new());
    }
    if v.is_string() {
        if let Some(s) = v.as_string() {
            return s.to_string().map_err(|e| format!("JS 字符串转换失败: {e}"));
        }
        return Ok(String::new());
    }
    if v.is_number() {
        return Ok(v.as_number().map(|n| n.to_string()).unwrap_or_default());
    }
    if v.is_bool() {
        return Ok(v.as_bool().map(|b| b.to_string()).unwrap_or_default());
    }
    match ctx
        .json_stringify(v)
        .map_err(|e| format!("JS JSON 序列化失败: {e}"))?
    {
        Some(s) => s
            .to_string()
            .map_err(|e| format!("JS JSON 字符串转换失败: {e}")),
        None => Ok(String::new()),
    }
}

