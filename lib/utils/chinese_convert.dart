/// 字级常用映射 + 高频歧义词匹配；完整 OpenCC 词典仍可作为后续数据扩展。
class ChineseConvert {
  ChineseConvert._();

  static String apply(String input, int mode) {
    if (mode == 1) return _map(_applyPhrases(input, _t2sPhrases), _t2s);
    if (mode == 2) return _map(_applyPhrases(input, _s2tPhrases), _s2t);
    return input;
  }

  static String _applyPhrases(String input, Map<String, String> phrases) {
    var result = input;
    final keys = phrases.keys.toList()
      ..sort((a, b) => b.length.compareTo(a.length));
    for (final key in keys) {
      result = result.replaceAll(key, phrases[key]!);
    }
    return result;
  }

  static String _map(String input, Map<int, int> table) {
    if (input.isEmpty) return input;
    final out = StringBuffer();
    for (final r in input.runes) {
      out.writeCharCode(table[r] ?? r);
    }
    return out.toString();
  }

  static final Map<int, int> _s2t = Map.unmodifiable(_kS2t);
  static final Map<int, int> _t2s = Map.unmodifiable({
    for (final e in _kS2t.entries) e.value: e.key,
  });

